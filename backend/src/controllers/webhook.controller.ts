import { Request, Response } from 'express';
import crypto from 'node:crypto';
import { prisma } from '../config/prisma.js';
import { prProcessorService } from '../services/prProcessor.service.js';
import { sendSuccess, sendError } from '../utils/response.js';

export class WebhookController {
  handle = async (req: Request, res: Response): Promise<void> => {
    try {
      const event = req.headers['x-github-event'] as string;
      const deliveryId = (req.headers['x-github-delivery'] as string) || crypto.randomUUID();
      const payloadBuffer = req.rawBody || Buffer.from(JSON.stringify(req.body));
      const payloadDigest = crypto.createHash('sha256').update(payloadBuffer).digest('hex');

      // V11 & V12: Deduplicate or reject tampered deliveries
      const existingDelivery = await prisma.webhookDelivery.findUnique({
        where: { deliveryId },
      });

      if (existingDelivery) {
        if (existingDelivery.payloadDigest !== payloadDigest) {
          console.error(`🚨 [WebhookAdmission] Tampered delivery attempt for ${deliveryId}`);
          sendError(res, 'Tampered webhook delivery detected', 409);
          return;
        }

        console.log(`ℹ️ [WebhookAdmission] Duplicate delivery ${deliveryId} acknowledged idempotently.`);
        sendSuccess(
          res,
          {
            received: true,
            duplicate: true,
            deliveryId,
            status: existingDelivery.admissionStatus,
          },
          200
        );
        return;
      }

      // Handle ping event when webhook is registered
      if (event === 'ping') {
        console.log('🏓 GitHub Ping Webhook received');
        sendSuccess(res, { message: 'Pong! Webhook registered successfully.' });
        return;
      }

      if (event !== 'pull_request') {
        sendSuccess(res, { message: `Event ${event} ignored. Only 'pull_request' is handled.` });
        return;
      }

      const { action, pull_request, repository } = req.body;

      if (
        !repository ||
        !pull_request ||
        typeof repository.id !== 'number' ||
        repository.id <= 0 ||
        typeof pull_request.number !== 'number' ||
        pull_request.number <= 0
      ) {
        sendError(res, 'Invalid webhook payload structure', 400);
        return;
      }

      console.log(`📥 PR Event received: ${action} on ${repository.full_name} (#${pull_request.number})`);

      // Check if repository is active and confirmed in our database
      const dbRepo = await prisma.repository.findUnique({
        where: { githubRepoId: repository.id },
      });

      if (!dbRepo || !dbRepo.isActive || !dbRepo.desiredActive || dbRepo.provisioningState !== 'ACTIVE') {
        console.log(`⏭️ Repository ${repository.full_name} is not monitored or inactive.`);
        sendSuccess(res, { message: 'Repository is inactive, skipped processing' });
        return;
      }

      // Allowed PR actions
      const triggerActions = ['opened', 'synchronize', 'reopened'];
      if (!triggerActions.includes(action)) {
        sendSuccess(res, { message: `PR action '${action}' ignored` });
        return;
      }

      const headSha = pull_request.head?.sha || 'unknown-sha';
      const baseRef = pull_request.base?.ref || 'main';

      // V20: Check if head commit was produced by an automated documentation proposal (self-loop prevention)
      const matchingIntent = await prisma.commitIntent.findFirst({
        where: {
          repositoryId: dbRepo.id,
          prNumber: pull_request.number,
          OR: [
            { appliedCommitSha: headSha },
            {
              status: 'PENDING',
              expectedParentSha: pull_request.before || undefined,
            },
          ],
        },
        include: {
          proposal: true,
        },
      });

      if (matchingIntent) {
        console.log(
          `ℹ️ [WebhookAdmission] Detected self-generated documentation commit ${headSha} from proposal ${matchingIntent.proposalId}. Skipping analysis to prevent infinite loops.`
        );

        // If intent was still pending (webhook arrived before API call finished), reconcile it
        if (matchingIntent.status === 'PENDING') {
          await prisma.commitIntent.update({
            where: { id: matchingIntent.id },
            data: {
              status: 'CONFIRMED',
              appliedCommitSha: headSha,
            },
          });

          await prisma.docProposal.update({
            where: { id: matchingIntent.proposalId },
            data: {
              status: 'APPLIED',
              commitSha: headSha,
            },
          });
        }

        // Record delivery as admitted and skipped
        await prisma.webhookDelivery.create({
          data: {
            deliveryId,
            repositoryId: dbRepo.id,
            event,
            action,
            headSha,
            payloadDigest,
            admissionStatus: 'SKIPPED_SELF_COMMIT',
            admissionReason: `Generated by proposal ${matchingIntent.proposalId}`,
          },
        });

        sendSuccess(res, {
          received: true,
          skipped: true,
          reason: 'Self-generated documentation commit ignored to prevent loop',
          headSha,
        });
        return;
      }

      // Atomic enrollment of ProcessingRun and WebhookDelivery (ADR 0004, V11, V13)
      const run = await prisma.processingRun.upsert({
        where: {
          repositoryId_prNumber_headSha: {
            repositoryId: dbRepo.id,
            prNumber: pull_request.number,
            headSha,
          },
        },
        update: {},
        create: {
          repositoryId: dbRepo.id,
          prNumber: pull_request.number,
          prTitle: pull_request.title || 'Untitled PR',
          headSha,
          baseRef,
          status: 'QUEUED',
          attemptCount: 0,
          maxAttempts: 3,
        },
      });

      await prisma.webhookDelivery.create({
        data: {
          deliveryId,
          repositoryId: dbRepo.id,
          event: 'pull_request',
          action,
          headSha,
          payloadDigest,
          admissionStatus: 'ADMITTED',
          processingRunId: run.id,
        },
      });

      // Synchronize legacy WebhookLog for backward compatibility
      await prisma.webhookLog
        .create({
          data: {
            id: run.id,
            repositoryId: dbRepo.id,
            prNumber: pull_request.number,
            prTitle: pull_request.title || 'Untitled PR',
            status: 'PENDING',
            rawDiffSize: 0,
          },
        })
        .catch(() => {
          // Ignored if mapped log already exists
        });

      // Dispatch processing
      prProcessorService
        .processPullRequest(run.id, dbRepo.id, pull_request, repository)
        .catch((err) => console.error('💥 Background PR processing failed unexpectedly:', err));

      // Respond promptly to GitHub with HTTP 202 Accepted (Job safely persisted)
      sendSuccess(
        res,
        {
          message: 'Webhook received and admitted to persistent queue',
          deliveryId,
          runId: run.id,
          status: run.status,
        },
        202
      );
    } catch (error) {
      console.error('❌ WebhookController.handle error:', error);
      sendError(res, 'Internal server error while processing webhook', 500);
    }
  };

  listLogs = async (req: Request, res: Response): Promise<void> => {
    try {
      if (!req.user) {
        sendError(res, 'Unauthorized', 401);
        return;
      }

      const page = req.query.page ? Math.max(1, Number(req.query.page)) : 1;
      const limit = req.query.limit ? Math.min(100, Math.max(1, Number(req.query.limit))) : 50;
      const skip = (page - 1) * limit;

      const whereClause: any = {
        repository: {
          userId: req.user.id,
        },
      };

      if (req.query.status && typeof req.query.status === 'string') {
        whereClause.status = req.query.status;
      }

      const [total, logs] = await Promise.all([
        prisma.webhookLog.count({ where: whereClause }),
        prisma.webhookLog.findMany({
          where: whereClause,
          orderBy: { createdAt: 'desc' },
          skip,
          take: limit,
          include: {
            repository: {
              select: {
                name: true,
                fullName: true,
                owner: true,
              },
            },
          },
        }),
      ]);

      const totalPages = Math.ceil(total / limit) || 1;

      sendSuccess(res, {
        items: logs,
        pagination: {
          page,
          limit,
          total,
          totalPages,
        },
      });
    } catch (error) {
      console.error('❌ WebhookController.listLogs error:', error);
      sendError(res, 'Failed to fetch webhook logs', 500);
    }
  };
}

export const webhookController = new WebhookController();
