import { ValidatedAnalysis, AnalysisUsage } from '../types/analysis.js';

export function formatReviewComment(options: {
  analysis: ValidatedAnalysis;
  usage: AnalysisUsage | null;
  truncated: boolean;
}): string {
  const { analysis, usage, truncated } = options;

  const severityIconMap: Record<string, string> = {
    info: '💡',
    warning: '⚠️',
    critical: '🚨',
  };

  const categoryBadgeMap: Record<string, string> = {
    feat: '✨ Feature',
    fix: '🐛 Bug Fix',
    refactor: '♻️ Refactor',
    docs: '📚 Documentation',
    test: '🧪 Tests',
    chore: '🔧 Chore',
    security: '🔒 Security',
    performance: '⚡ Performance',
    breaking_change: '💥 Breaking Change',
  };

  const categoriesText = analysis.categories
    .map((c) => `\`${categoryBadgeMap[c] || c}\``)
    .join(' ');

  let comment = `## 🤖 GitDocs AI Review <!-- gitdocs-review -->\n\n`;

  // Categories & Summary
  comment += `**Categories:** ${categoriesText}\n\n`;
  comment += `${analysis.summary}\n\n`;

  if (truncated) {
    comment += `> ℹ️ **Notice:** The PR diff was truncated because it exceeded maximum processing limits. Analysis covers prioritized changes.\n\n`;
  }

  // Technical Findings
  if (analysis.findings.length > 0) {
    comment += `### 🔍 Technical Findings\n\n`;

    for (const finding of analysis.findings) {
      const icon = severityIconMap[finding.severity] || '💡';
      const location = finding.lineRange
        ? `\`${finding.file}\` (${finding.lineRange})`
        : `\`${finding.file}\``;

      comment += `#### ${icon} ${finding.title}\n`;
      comment += `- **Location:** ${location}\n`;
      comment += `- **Details:** ${finding.message}\n`;
      if (finding.evidence) {
        comment += `- **Evidence:** \`${finding.evidence}\`\n`;
      }
      comment += `\n`;
    }
  }

  // Documentation Update Proposals
  if (analysis.suggestedDocUpdate) {
    const doc = analysis.suggestedDocUpdate;
    comment += `### 📝 Documentation Suggestion (Proposed)\n\n`;
    comment += `**Target:** \`${doc.targetFile}\` — *${doc.title}*\n\n`;
    comment += `${doc.description}\n\n`;
    comment += `\`\`\`markdown\n${doc.operations.map(op => `Replace:\n${op.oldText}\nWith:\n${op.newText}`).join('\n\n')}\n\`\`\`\n\n`;
    comment += `> 💡 *To apply this suggestion to \`${doc.targetFile}\`, visit the GitDocs dashboard to review and approve the proposal.*\n\n`;
  }

  // Footer Metadata
  comment += `---\n`;
  const modelInfo = usage?.model ? `Model: \`${usage.model}\`` : 'Model: AI Reviewer';
  const tokensInfo =
    usage?.inputTokens && usage?.outputTokens
      ? ` • Tokens: ${usage.inputTokens} prompt / ${usage.outputTokens} response`
      : '';

  comment += `*Generated by GitDocs • ${modelInfo}${tokensInfo}*`;

  return comment;
}
